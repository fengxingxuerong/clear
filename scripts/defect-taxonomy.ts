/** 全部签名名（组名:签名名），供自检比对 */
export function allTaxonomySignatures(): string[] {
  return DEFECT_TAXONOMY.flatMap((e) => e.signatures);
}

/** 按类别查历史修复 */
export function fixesFor(category: DefectCategory): string[] {
  return DEFECT_TAXONOMY.find((e) => e.category === category)?.fixes ?? [];
}

/** 查**从未修过**的类别——这些是下次体检的优先方向 */
export function unfixedCategories(): DefectCategory[] {
  return DEFECT_TAXONOMY.filter((e) => e.fixes.length === 0).map((e) => e.category);
}
