/**
 * defect-taxonomy.ts —— 缺陷类别对照表（v0.9.24 新增）
 *
 * ## 为什么需要它
 *
 * `scan-bugs.ts` 有 13 组签名、30+ 条探针。它们能抓到「有问题的输出」，
 * 但**没人能从签名本身看出「这一条在防哪一类缺陷」**。后果有两个：
 *
 *   1. 新增签名时容易重复造轮子——不知道已有的签名是否已经覆盖同一类。
 *   2. 修 bug 时无法反查——发现一条签名命中，想知道「历史上这类问题修过几次、
 *      根因分别是什么」，得全文 grep。
 *
 * 本表把散落在各组里的签名映射到**统一的缺陷类别**，并记录每类的
 * 历史修复与根因摘要。新增签名时：先查本表有没有同类，
 * 再决定是复用已有签名还是新建。
 *
 * ## 类别的划分依据
 *
 * 不是按「签名长什么样」，而是按**根因在哪一层**——
 * 因为修复动作是按层决定的：
 *
 *   词表层    → 改 `humanize-vocab.ts` / `humanize-zhuque.ts` 的数据
 *   守卫层    → 改 `humanize-guard.ts`（GUARD_AFTER / GUARD_BEFORE / 类别规则）
 *   替换层    → 改 `replaceVocab` 里的 clash* 判据
 *   切分层    → 改 `fragmentCanStand` / `boostBurstinessByCutting`
 *   标尺层    → 改 `aiScore` / `fingerprintCheck`
 *   管线顺序  → 改 `humanize.ts` 主流程的调用顺序
 *
 * 「类别」= 缺陷类型 + 根因层。两者合起来才能回答「这条该怎么修」。
 */

/** 根因层 —— 决定修复动作要动哪个文件 */
export type DefectLayer =
  "词表层" | "守卫层" | "替换层" | "切分层" | "标尺层" | "管线顺序" | "外部不可修";

/**
 * 缺陷类别。
 *
 * 命名原则：描述**可观察到的破坏形态**，不描述修法。
 * 这样同一类别可以由不同层的根因产生，将来修法换了类别也不用改。
 */
export type DefectCategory =
  /** 替身与邻词各自合法、合起来才成病（最难查的一类） */
  | "第三类盲区·拼接成词"
  /** 替身与右邻/左邻的单字碰撞（叠字、量词被切） */
  | "单字碰撞"
  /** 替身落在错误的语法位（名词位、状语位、定语位） */
  | "语法位错配"
  /** 替身的搭配对象不兼容（动宾/动补、抽象宾语） */
  | "搭配不当"
  /** 语体错位（书面语换成口语词，或反过来） */
  | "语体错位"
  /** 切句把句子切坏（骨架词独句、谓语被切出、光杆孤句） */
  | "切句破坏"
  /** 注入器重复叠加（垫词复读、双开头） */
  | "注入叠加"
  /** 标尺自身的问题（节奏过平、CV 判别力） */
  | "标尺失效"
  /** 格式保真（段落丢失、URL/时间乱码） */
  | "格式损坏"
  /** 文本保真（数字篡改、段落丢失） */
  | "内容失真";

export interface DefectTaxonomyEntry {
  /** 缺陷类别 */
  category: DefectCategory;
  /** 根因层 */
  layer: DefectLayer;
  /** 该类别的定义与判定要点 */
  desc: string;
  /** 覆盖此类的签名（组名:签名名） */
  signatures: string[];
  /** 历史修复记录：版本 + 根因摘要。空数组表示从未修过（= 可能仍有活实例） */
  fixes: string[];
}

