const STRIPS: Array<[string, (t: string) => string]> = [
  ["句尾单字语气词", (t) => t.replace(/([\u4e00-\u9fa5])[嗯啊哦嗨咳呣啧诶哈嗼呵吧呢嘛呀]{1,2}([。！？])/g, "$1$2")],
  ["句首垫词+逗号", (t) => t.replace(/(?<=^|[。！？\n]\s*)(?:说真的|说实话|讲真|要我说|说白了|我寻思着|我寻思|老实讲|不瞒你说|你别说|按我的经验|其实|说到底|具体来说|换句话说|简单说|总体而言|坦白讲|老实说|严格来说|客观来讲|有一说一|不吹不黑|平心而论|反正|所以说|总之|总的来说|反过来看|说实话)[，,]/g, "")],
  ["碎片/垫词独句", (t) => t.replace(/(?:^|[。！？\n]\s*)(?:就这样|怎么说呢|反正就那样|你懂的|没别的意思|话是这么说|道理是这个道理|也不是不行|差不多得了|懂的都懂|你别不信|这谁说得准呢|也不是没有道理|行吧|随你怎么说|反正我信了|无话可说|是啊|哦对|说白了|讲真|说真的)[。！？]/g, "")],
  ["长模板插话", (t) => t.replace(/(?:^|[。！？\n]\s*)(?:你可能会问——这不是理所当然的吗？其实不然。|例子呢？|我随便举一个你就懂了。|真的假的？|这事儿还真不是我瞎编。|为啥这么说？|因为事实就摆在眼前。|有人要抬杠了——别急，我慢慢跟你捋。|不信？|那你自己试试就知道了。|我寻思着。)[。！？]?/g, "")],
  ["方言漏网", (t) => t.replace(/寻思着/g, "想").replace(/寻思/g, "想").replace(/瞅/g, "看").replace(/唠/g, "谈")],
];

for (const [label, text, genre] of [
  ["论说", EXPO_MULTI, "main"],
  ["叙事", NARR_MULTI, "narrative"],
  ["对话", DIALOG_MULTI, "dialogue"],
  ["人写", HUMAN_MULTI, "humanHand"],
] as const) {
  const before = aiScore(text);
  const out = humanize(text, { intensity: 0.9, zhuqueMode: true, genre, seed: 7 });
  const after = aiScore(out);
  console.log(`\n${"=".repeat(78)}`);
  console.log(`【${label}】原文 ${before.score} → 去味后 ${after.score}  (句式 ${before.structureHits}→${after.structureHits}, 病词 ${before.brokenHits}→${after.brokenHits})`);
  console.log(`--- 输出 ---`);
  console.log(out.slice(0, 600));
  console.log(`--- 逐项剥夺 ---`);
  for (const [n, fn] of STRIPS) {
    const t = fn(out);
    console.log(`  −${n.padEnd(14)} → ${String(aiScore(t).score).padStart(3)} (句式 ${aiScore(t).structureHits})`);
  }
  let all = out;
  for (const [, fn] of STRIPS) all = fn(all);
  console.log(`  −全部            → ${String(aiScore(all).score).padStart(3)} (句式 ${aiScore(all).structureHits})`);
}
