function run(set: string[][], tag: string) {
  console.log(`\n========== ${tag} ==========`);
  const probs: number[] = [];
  for (const [name, text] of set) {
    const r = detectAI(text);
    probs.push(r.probability);
    const mark = r.level === "high" ? "🔴" : r.level === "medium" ? "🟡" : "🟢";
    console.log(
      `${mark} ${name.padEnd(24)} ${String(r.probability).padStart(3)}%  ${r.levelText}（置信 ${r.confidence}）  CV=${r.stats.sentenceCV} TTR=${r.stats.ttr} 句${r.stats.sentences}`
    );
    const top = r.features.filter((f) => f.value > 0.55).map((f) => f.name).slice(0, 4);
    if (top.length) console.log(`    高分特征: ${top.join("、")}`);
  }
  const avg = Math.round(probs.reduce((a, b) => a + b, 0) / probs.length);
  console.log(`${tag} 均值 ${avg}%  区间 ${Math.min(...probs)}~${Math.max(...probs)}`);
  return probs;
}

const aiProbs = run(AI_SAMPLES, "AI 样本（应判 high ≥62）");
const huProbs = run(HUMAN_SAMPLES, "真人样本（应判 human <38）");

const aiMin = Math.min(...aiProbs);
const huMax = Math.max(...huProbs);
console.log(`\n===== 可分性 =====`);
console.log(`AI 最低分 ${aiMin} / 真人最高分 ${huMax}`);
console.log(aiMin > huMax ? `✅ 完全可分，安全阈值区间 (${huMax}, ${aiMin})` : `❌ 区间重叠，需调权重（重叠 ${huMax - aiMin}）`);
