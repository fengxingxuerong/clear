/**
 * 标定语料集：区分「像人写」与「引擎污染」。
 *
 * 用途：为 aiScore 的检测器提供标定与回归基线。
 * 纪律：每加一个检测器，都要跑本文件——
 *   HUMAN 组必须全部判低分，MACHINE 组必须全部判高分；
 *   任何一侧越界都说明检测器过宽或过窄，需要回去调权重，而不是改语料。
 *
 * 另一条纪律：语料必须来自**真实文本**或**真实引擎输出**。
 * 自己臆造的"典型 AI 味"往往带上臆造者的偏见，标定出的阈值会失真。
 * 标 §ENGINE-REAL 的条目是从 humanize() 实际输出中摘录的，不要手改。
 */

export interface CalibrationSample {
  id: string;
  genre: "main" | "narrative" | "dialogue" | "humanHand";
  /** 期望判定 */
  expect: "human" | "machine";
  /** 该样本想考察的具体特征（便于失败时定位） */
  probes: string[];
  text: string;
}

