/**
 * scripts/_pad_legit.ts —— 垫词的"真人合法性"判定（临时）
 *
 * 核心定性问题：`其实，` / `说实话，` 这类句首垫词，
 * 在真人中文写作里到底是正常表达还是机器味？
 *
 * 标尺当前判定：出现即 36 分（3e 污染率）。
 * 但标尺的设计初衷是抓"机械堆砌"，不是抓"单个使用"。
 *
 * 手法：构造三组对照
 *   A) 真人风格：单个垫词，隔很远，一篇文章只用一次
 *   B) 机器风格：垫词高密度堆砌
 *   C) 干净：完全无垫词
 * 看 A 是否被误伤（这是关键 —— 若 A 被罚分，说明标尺过严）
 */
import { aiScore } from "../src/engine/humanize-metrics";

const CASES: Array<{ id: string; text: string; expect: string }> = [
  {
    id: "A1-单个其实（散文）",
    expect: "真人",
    text: "我小时候住在胡同里，院里有棵大槐树。夏天傍晚，大人搬着小板凳在树下乘凉，孩子们追着萤火虫满院跑。其实，那时候的日子过得挺紧巴，但没人觉得苦。",
  },
  {
    id: "A2-单个说实话（评论）",
    expect: "真人",
    text: "这个方案我看了好几遍，技术上没什么大问题，成本也压得住。说实话，我唯一担心的是工期，三个月要落地，团队得连轴转。",
  },
  {
    id: "A3-单个讲真（口语随笔）",
    expect: "真人",
    text: "前阵子去爬了趟黄山，累是真累，腿酸了三天。讲真，山顶那阵云海值这个罪。下次想挑个秋天再去一趟。",
  },
  {
    id: "A4-两个垫词隔很远",
    expect: "真人",
    text: "这个项目从立项到现在快一年了。中间遇到不少坎，好在都趟过来了。其实，最难的不是技术选型，是把几个部门的诉求拧到一块儿。现在回头看，当初坚持做下来是对的。说实话，我还挺想再干一个这样的项目。",
  },
  {
    id: "B1-垫词堆砌（机器）",
    expect: "机器",
    text: "说白了，这个问题的本质其实就是利益分配。你懂的，大家都不傻。说到底，还是要看谁能扛住压力。话说回来，这事儿也不是一天两天了。",
  },
  {
    id: "B2-每句都带垫词（机器）",
    expect: "机器",
    text: "其实，这个问题很复杂。说实话，我们不能忽视它。讲真，需要认真对待。老实讲，这很重要。",
  },
  {
    id: "C1-干净书面",
    expect: "真人",
    text: "我国教育资源配置存在区域不平衡的问题。随着国家对教育投入的持续加大，这一状况正在逐步改善。教育公平的实现需要全社会的共同努力。",
  },
];

console.log("样本".padEnd(22) + "期望  得分  套话 句式  判定");
console.log("-".repeat(62));
for (const c of CASES) {
  const bd = aiScore(c.text);
  const verdict = bd.score >= 29 ? "机器" : "真人";
  const ok = verdict === c.expect ? "✅" : "❌ 错判";
  console.log(
    `${c.id.padEnd(20)} ${c.expect.padEnd(5)} ${String(bd.score).padStart(4)}  ${String(bd.formulaicHits).padStart(3)}  ${String(bd.structureHits).padStart(3)}   ${verdict} ${ok}`,
  );
}
