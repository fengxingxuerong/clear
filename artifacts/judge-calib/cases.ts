/**
 * judge-calib/cases.ts —— 裁判校准夹具集
 *
 * ## 设计要点（这三条决定了校准有没有意义）
 *
 * ① **缺陷句必须埋在正常上下文里**：不能只给孤立病句（那测的是"这像病句吗"，
 *    跟实战无关）。真实场景是 LLM 要在一整段产出里挑出问题句。
 * ② **必须有无缺陷对照（clean）**：只测召回等于鼓励裁判"见谁都报"。
 *    一份把干净人写稿也报成病句的裁判，召回 100% 也毫无价值。
 * ③ **probe 片段用于匹配**：判定"裁判是否发现了该缺陷"，靠 probe 的字符级
 *    最长公共子串（≥4 字）匹配——不比字面相等，因为裁判复述原句时会改标点。
 *
 * 22 条 defect 一一对应 scan-bugs v8.0 的 22 条探针（v0.9.44 现状）。
 */
import { splitSentences } from "../../src/engine/humanize-text.ts";

export interface Case {
  id: string;
  kind: "defect" | "clean";
  /** 送给裁判的完整文本（缺陷句埋在其中） */
  text: string;
  /** 该缺陷的探针名（clean 类为空） */
  probe?: string;
  /** 缺陷关键片段：裁判引用的句子含它的 ≥4 字连续子串即判"已发现" */
  frag?: string;
  note?: string;
}

/** 去标点空白（编号对齐与片段匹配共用同一种归一化） */
export function normalize(s: string): string {
  return s.replace(/[\s，。！？、；：""''（）《》"'.,!?;:()[\]]/g, "");
}

/** 切句 + 定位缺陷所在句号（1 基）。clean 返回 null。
 *
 *  ⚠️ 这个函数是"编号对齐判定"的地基：v2 变体把句子编号喂给裁判，
 *  裁判只需回答"第几句有问题"。比起 v1 的字符串模糊匹配，它有两个好处：
 *   ① 定位偏移能被正确识别（裁判报错了句号 = 真错，不是漏报）；
 *   ② 不再受"裁判复述原句时改了标点/截断"影响。
 *  放在这里而不是 run.ts，是为了 rescore 能用同一套编号重算已落盘的结果。 */
export function analyze(c: Case): { sentences: string[]; defectIdx: number | null } {
  const sentences = splitSentences(c.text);
  if (c.kind !== "defect" || !c.frag) return { sentences, defectIdx: null };
  const f = normalize(c.frag);
  const norms = sentences.map(normalize);
  // 第 1 轮：≥3 字连续子串（宽松接受，取最长）
  let idx: number | null = null;
  let bestLen = 0;
  for (let len = Math.min(f.length, 20); len >= 3; len--) {
    for (let st = 0; st + len <= f.length; st++) {
      const piece = f.slice(st, st + len);
      const hit = norms.map((n, i) => (n.includes(piece) ? i + 1 : 0)).filter(Boolean);
      if (hit.length === 1 && len > bestLen) {
        bestLen = len;
        idx = hit[0];
      }
    }
    if (idx !== null) break;
  }
  if (idx !== null) return { sentences, defectIdx: idx };
  // 第 2 轮：2 字片段（「首先」「准备」这类极短 frag——v0.9.44 实测 2 条定位失败）。
  // ⚠️ 必须要求**全局唯一命中**：2 字片段在多句里重复出现的概率很高，
  //    不唯一就宁可判"定位失败"，也不能猜（猜错会让基准答案本身是错的）。
  if (f.length === 2) {
    const hit = norms.map((n, i) => (n.includes(f) ? i + 1 : 0)).filter(Boolean);
    if (hit.length === 1) return { sentences, defectIdx: hit[0] };
  }
  return { sentences, defectIdx: null };
}

