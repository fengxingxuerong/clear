export function startsWithConnector(s: string): boolean {
  // INTERJECTIONS 也要算：避免"要我说，有意思的是，"这类词典替身+垫词的双开头叠罗汉
  return (
    LEADING_CONNECTORS.some((c) => s.startsWith(c)) ||
    INTERJECTIONS.some((c) => s.startsWith(c)) ||
    s.startsWith("有意思的是")
  );
}

// 句尾偶尔软化（尾助词）；"呗/咯/哟"太跳，议论文语境里像抽风，弃用
export const SOFT_ENDINGS = ["吧", "呢", "嘛", "呀", "哈"];

// 光杆谓语开头（切句守卫用）：这些词开头的分句依赖前半句的主语，不能独立成句
export const PREDICATE_ONLY_START =
  /^(成为|使得|导致|意味着|证明|表明|从而|进而|方能|才能|便是|即是|依然|仍然是?)/;

/** 切出来的后半句能否独立成句：光杆谓语开头、或"也/还/更+动词"（共享主语）、
 *  或"对于X具有Y"（缺主语的评述句）都不能切，否则产生无主句病句 */
export function fragmentCanStand(s: string): boolean {
  if (PREDICATE_ONLY_START.test(s)) return false;
  // "也深刻影响着"：副词+动词带体标记（着/了/过）说明谓语承接前句主语
  if (/^(?:也|还|更|又)[\u4e00-\u9fa5]{0,5}(?:着|了|过)/.test(s)) return false;
  // "对于系统性知识建构具有……"：介词短语直接挂谓语，缺主语
  if (/^对于[\u4e00-\u9fa5]{1,10}(?:具有|是|有|需要|值得)/.test(s)) return false;
  return true;
}

