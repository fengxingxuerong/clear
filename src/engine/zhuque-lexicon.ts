/** 第一人称与主观标记（真人显著更高） */
export function rePersonal(): RegExp {
  return /(我|我们|咱|你|您|我觉得|个人|身边|记得|那次|当时|小时候|昨天|上周|我家|朋友)/g;
}

/** 具体细节标记：数字、专名、时间、地点、中文数量词（"两百多块""快十年了"都是真人痕迹） */
export function reConcrete(): RegExp {
  return /([0-9０-９]+[年月日%％元块个次万亿度公里分秒]|[一二三四五六七八九十百千万亿两几]{1,3}[块元个年月天次度岁遍]|[A-Za-z][A-Za-z0-9-]{2,}|第[一二三四五六七八九十]+[章节部])/g;
}

/** 四字格/对仗排比（AI 爱堆） */
export function reIdiomLike(): RegExp {
  return /[\u4e00-\u9fa5]{4}(?:、[\u4e00-\u9fa5]{4}){1,}/g;
}

/** 判断句式与情态词密度（AI 写论述文的骨架动词）
 *
 *  ⚠️ 历史坑（2026-10-03 核实，勿重蹈）：detector 与 zhuque 曾各写一份，且已漂移。
 *  本文件**刻意保留两个变体**，不强行统一——因为统一会移动 zhuque 的 x 轴打分，
 *  而标定漂移棘轮已压满（6/18 点、Δmax 35/35），任何 x 轴移动都会把它顶红。
 *  真要统一必须与四条体裁线重拟合一并评估。
 *
 *  两者的真实差异（其余逐字相同）：
 *   - `reModalDetector()`（detector 用）：多 `需要进一步` 与 `值得注意的是`
 *     · `需要进一步` 是**死分支**——JS 正则交替首次匹配优先，前面的 `需要` 先命中，
 *       故该分支永不生效（实测 `"需要进一步".match(re)` 返回 `["需要"]`）。保留是为
 *       零行为变化；下次做 x 轴重拟合时应删掉。
 *     · `值得注意的是` 与上面的 `FORMULAIC` 是同一处被两个特征各计一次
 *       （套话密度 + 情态密度），属既有口径，不擅自改。
 *   - `reModalZhuque()`（zhuque 用）：不含上述两项（`值得注意的是` 只在 FORMULAIC 侧计）。
 *
 *  drift 守卫见 `zhuque-lexicon.test.ts`：断言两者差异**只允许**是这 2 个词。
 */
export function reModalDetector(): RegExp {
  return /(应该|应当|必须|需要|需要进一步|有助于|意味着|表明|说明|能够|可以|我们要|值得注意的是|不仅|而且|既要|也要)/g;
}

/** @see reModalDetector 的说明——这是 zhuque 检测器的窄口径变体 */
export function reModalZhuque(): RegExp {
  return /(应该|应当|必须|需要|有助于|意味着|表明|说明|能够|可以|我们要|既要|也要|不仅|而且)/g;
}
