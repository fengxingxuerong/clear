/**
 * humanize-quality-v0922.test.ts —— v0.9.22 语言质量守卫的防漏测试
 *
 * ## 为什么要单独一个文件
 *
 * v0.9.22 修的四类破坏（级联替换 / 叠字漏左侧 / 口语结果动词接抽象宾语 / 裸骨架独句）
 * **全都不是"某个具体词"的错，是一类组合的错**。既有 `humanize-quality.test.ts` 里
 * 每条用例都绑定具体词（「靠对」「对口味」「得了了」），它的语义是"这几个老坑别复发"——
 * 换一批搭配就一条都碰不到（2026-10-04 实测：随手写的 5 段新文本立刻命中 3 组新的）。
 *
 * 所以这里刻意做**类别级**断言 + 三层防漏：
 *   ① 正向：多体裁语料 × 多档 × 多种子，类别级探针零命中；
 *   ② **自检**：每条探针必须能命中一个人工构造的坏串——
 *      证明"零命中"是引擎干净，不是正则写错、也不是比对逻辑空转；
 *   ③ **字符级一致性**：探针正则与 `scan-bugs.ts` 里登记的逐字相同，防两边各改各的漂移。
 *
 * ② 是这套测试的关键。只有正向断言的守卫在最危险的情形下会假绿：
 * 正则失效 → 永远零命中 → 测试永远通过。自检把"探针本身会不会响"也变成断言。
 *
 * ## 敏感度实测（2026-10-04，缺陷注入，别靠猜）
 *
 * 每条断言都做了"把对应守卫改坏 → 测试是否变红"的注入验证，结果**参差不齐**，如实登记：
 *
 * | 断言 | 注入方式 | 结果 |
 * |---|---|---|
 * | 口语结果动词+抽象宾语 | `clashAbstract = false` | **红**（命中「搞出健全的监管框架」）✅ 单条敏感 |
 * | 落地前置判据（定语位） | 去掉 `from === "落地"` 守卫 | **红**（产出「在产业真正做出来这块」）✅ 单条敏感 |
 * | 三连叠字 | 只去掉左侧判据 | 绿 —— 需**同时**回退模板正则（残留"审视"）才红 ⇒ 组合敏感 |
 * | 骨架词独立成句 | 去掉独句还原那段 | **绿** —— 当前引擎下已无可观测触发路径 ⇒ 纵深断言 |
 * | 级联守卫（端到端） | `cascade = false` | **绿** —— 被「落地」前置判据兜住 ⇒ 靠白盒断言钉住 |
 *
 * 三条"绿"的不删，但**不许当成主力门禁**：它们防的是未来（引擎改动重新打通触发路径）
 * 以及组合失效。真正单条敏感的只有前两条 + 白盒那条。
 */
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { humanize, wouldCascade } from "./humanize";
import { VOCAB } from "./humanize-vocab";
import { GUARD_BEFORE } from "./humanize-guard";

/** 多体裁语料：换体裁＝换一批搭配，这是 v7.0 签名式探针覆盖不到的面 */
const CORPUS: [string, string][] = [
  [
    "政务论说",
    "随着人工智能技术的不断发展，自然语言处理已经成为当前学术界与产业界共同关注的重要研究方向。\n首先，从技术演进的角度来看，大语言模型的出现极大地推动了相关领域的技术变革。值得注意的是，模型规模的持续扩大不仅带来了性能的显著提升，也为下游应用提供了坚实的支撑。\n其次，在产业落地层面，越来越多的企业开始将相关技术广泛应用于智能客服、内容生成、辅助办公等多个场景。\n再次，从治理与合规的角度审视，技术的快速发展也带来了不容忽视的伦理风险。因此，建立健全的监管框架具有重要的战略意义。\n综上所述，只有在技术创新与风险防控之间取得平衡，才能真正实现可持续的高质量发展。",
  ],
  [
    "产品介绍",
    "本产品基于先进的分布式架构设计，能够为用户提供高效、稳定、安全的数据处理能力。\n一方面，系统采用了多层次的缓存机制，大幅降低了请求延迟；另一方面，通过智能调度算法，实现了资源的动态分配与优化配置。\n此外，平台还提供了丰富的开放接口，便于开发者进行二次集成。无论是中小型团队还是大型企业，都可以借助该平台显著提升自己的研发效率。\n总的说来，该产品致力于为用户创造长期价值，助力企业实现数字化转型。",
  ],
  [
    "学术摘要",
    "本文旨在探讨城市绿地空间格局对居民心理健康的影响机制。研究以某二线城市为案例，运用空间句法与问卷调查相结合的方法进行分析。\n研究结果表明，绿地可达性与居民的心理健康水平呈显著正相关。与此同时，绿地的植被多样性也对情绪恢复具有积极作用。\n值得注意的是，不同年龄段的人群对绿地的使用需求存在显著差异。因此，在城市绿地规划中应当充分考虑人群的异质性特征。\n本研究的发现对于优化城市绿地布局、提升公共空间品质具有一定的参考价值。",
  ],
];

/** 三连叠字：级联替换 / 叠字漏侧的共同产物（「从治理与合规看看看」） */
const RE_TRIPLE = /([\u4e00-\u9fa5])\1{2,}/;
/**
 * 裸骨架独立成句：连接词被切成独句（「再说。」「再次。」）。
 * ⚠️ 源串**逐字复制**自 `scan-bugs.ts` 的 v8.0 登记值（含 \uXXXX 转义写法），
 *    不要"顺手美化"成中文句号/中文顿号——字符级一致性断言会立刻变红，
 *    而那正是它存在的意义：门禁与测试必须查同一条正则。
 */
const RE_BARE_SKELETON =
  /(?:^|\n|\u3002|\uff01|\uff1f)(?:\u9996\u5148|\u5176\u6b21|\u518d\u8bf4|\u53e6\u5916|\u6b64\u5916|\u603b\u7684\u6765\u770b|\u603b\u800c\u8a00\u4e4b|\u603b\u7684\u8bf4\u6765|\u6700\u540e)\u3002/;
/** 口语结果动词 + 抽象名词宾语：动结式口语动词要求宾语是具体物（「搞出健全的监管框架」） */
const RE_COLLOQUIAL_ABSTRACT =
  /(?:搞出|弄出|干出|整出|搞成|弄成)[\u4e00-\u9fa5]{0,6}(?:框架|机制|体系|格局|价值|水平|质量|效率|意义|能力|模式|结构|制度|规范|标准|流程|生态|共识|关系|布局|目标|监管|治理|服务|管理|指标|模型|方案|路径|思路|逻辑|规则|秩序|信誉|口碑|信任|权威|优势|潜力|空间|挑战|风险|压力|动力|活力|合力|效力|竞争力|凝聚力|创造力|生产力)/;

const PROBES: [string, RegExp, string][] = [
  ["三连叠字", RE_TRIPLE, "从治理与合规看看看，这一块确实被反复提到"],
  ["骨架词独立成句", RE_BARE_SKELETON, "再说。在产业方面，我们已经有了初步的积累"],
  [
    "口语结果动词+抽象宾语",
    RE_COLLOQUIAL_ABSTRACT,
    "他们想搞出健全的监管框架，以此来降低风险",
  ],
];

describe("v0.9.22 类别级语言质量守卫", () => {
  it("②自检：三条探针都能命中人工构造的坏串（探针本身没失效）", () => {
    for (const [name, re, bad] of PROBES) {
      expect(bad.match(re), `探针「${name}」对自己该抓的坏串都不命中 → 正向断言全是假绿`).not.toBeNull();
    }
  });

  it("③字符级一致：探针正则与 scan-bugs.ts 登记的逐字相同", () => {
    // cwd 即仓库根（vitest 从根启动）；用 __dirname 在 ESM 下不可用
    const src = fs.readFileSync(path.resolve(process.cwd(), "scripts/scan-bugs.ts"), "utf-8");
    for (const [name, re] of PROBES) {
      expect(
        src.includes(re.source),
        `scan-bugs.ts 里找不到探针「${name}」的正则源串 → 两边已经漂移，门禁与测试查的不是同一件事`,
      ).toBe(true);
    }
  });

  it("①正向：3 体裁 × 3 档 × 10 种子，三条类别级探针零命中", () => {
    const intensities = [0.4, 0.6, 0.9];
    for (const [name, re] of PROBES) {
      for (const [corpusName, input] of CORPUS) {
        for (const it of intensities) {
          for (let seed = 0; seed < 10; seed++) {
            const out = humanize(input, { intensity: it, seed });
            const m = out.match(re);
            expect(m, `探针「${name}」命中｜${corpusName} 强度${it} seed${seed}：${m?.[0]}`).toBeNull();
          }
        }
      }
    }
  });

  it("级联守卫：替身本身是源词的 4 条链全部被登记为作废", () => {
    // 白盒钉住集合：全表只有这 4 条替身落回词表（至关重要→举足轻重 / 实现→落地 /
    // 推动→带动 / 持续→不断）。删掉任一条登记或把非源词误登记进来，这里都会红。
    for (const rep of ["举足轻重", "落地", "带动", "不断"]) {
      expect(wouldCascade(rep), `「${rep}」本身是源词，应被判为级联`).toBe(true);
    }
    for (const rep of ["一门心思", "就盯着", "方面", "调好"]) {
      expect(wouldCascade(rep), `「${rep}」不是源词，不该被判为级联（误判＝误伤正常替换）`).toBe(false);
    }
  });

  it("级联守卫（端到端，纵深）：政务语料不产出「真正真正做出来」", () => {
    // ⚠️ 诚实标注：这条**当前是纵深断言，不是主力断言**。
    // 「实现→落地」实测发生 16/40 seed，但随后「落地→真正做出来」被 v0.9.22 新加的
    // 「落地」前置使役判据拦掉了（"真正落地"前置是"真正"，不是使役动词），
    // 所以即使把级联判定整个拿掉，这条也仍然绿——它单独证明不了级联守卫在生效。
    // 它留着的理由：哪天「落地」前置守卫被移除或放宽，它会立刻变成主力断言。
    // 真正钉住"级联判定被调用"的是上面那条白盒断言。
    const src = "我们必须真正实现可持续的高质量发展，推动产业全面落地。";
    for (let seed = 0; seed < 30; seed++) {
      const out = humanize(src, { intensity: 0.9, seed });
      expect(out, `seed=${seed}：${out}`).not.toContain("真正真正做出来");
    }
  });

  it("语义漂移：删掉的那 6 个替身不再出现在任何输出里", () => {
    const banned: [string, string[]][] = [
      ["致力于", ["忙着"]],
      ["层面", ["那一摊"]],
      ["优化", ["改好"]],
      ["价值", ["好处"]],
      ["积极", ["主动"]],
      ["取得", ["见平衡"]],
    ];
    for (const [from, words] of banned) {
      for (const w of words) {
        expect(
          VOCAB[from] ?? [],
          `VOCAB.${from} 仍含被判定为语义漂移的替身「${w}」`,
        ).not.toContain(w);
      }
    }
  });

  it("守卫不误伤：谓语位「推动方案落地」仍会被替换（前置使役判据没把整条打死）", () => {
    const src = "下一步要推动方案落地，让流程真正跑起来，这需要各部门一起配合完成。";
    let replaced = 0;
    for (let seed = 0; seed < 30; seed++) {
      const out = humanize(src, { intensity: 0.9, seed });
      if (out.includes("真正做出来") || out.includes("真做出来")) replaced++;
    }
    expect(replaced, "整批种子一次都没替换「落地」→ 前置守卫过严，等于把这条替换废掉了").toBeGreaterThan(0);
  });

  it("定语位「在产业落地层面」不再产出「真正做出来那一摊」", () => {
    const src = "在产业落地层面，各家企业的进度差别很大，这一点在调研里体现得很清楚。";
    for (let seed = 0; seed < 30; seed++) {
      const out = humanize(src, { intensity: 0.9, seed });
      expect(out, `seed=${seed}：${out}`).not.toContain("真正做出来");
    }
  });

  it("「致力于」的新替身是副词性的，能接动词短语（不再是「忙着服务用户」式病句）", () => {
    const src = "该产品致力于为用户创造长期价值，并且持续投入基础能力的建设。";
    let replaced = 0;
    for (let seed = 0; seed < 30; seed++) {
      const out = humanize(src, { intensity: 0.9, seed });
      expect(out, `seed=${seed}：${out}`).not.toContain("忙着");
      expect(out, `seed=${seed}：${out}`).not.toContain("长期好处");
      if (out.includes("一门心思") || out.includes("就盯着")) replaced++;
    }
    expect(replaced, "整批种子一次都没替换「致力于」→ 该词条可能已失效（替换零发生 = 断言空转）").toBeGreaterThan(0);
  });

  it("GUARD_BEFORE.关注 仍登记着书面搭配状语（共同/密切/高度…）", () => {
    for (const w of ["共同", "密切", "高度", "广泛"]) {
      expect(GUARD_BEFORE.关注, `GUARD_BEFORE.关注 漏了「${w}」`).toContain(w);
    }
  });
});
