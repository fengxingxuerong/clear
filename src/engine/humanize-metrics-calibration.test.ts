/**
 * 标尺区分度回归（v0.9.7 新增）
 *
 * 缘起：2026-09-14 发现 aiScore 有一个**系统性盲区**——它认不出「口语化污染」。
 * 铁证：下面 M1 那段（"说真的，其实说白了，…"）任何中文母语者一眼看出是机器拼的，
 * 旧标尺给 **0 分**。四个旧维度全部落空：套话不在 VOCAB、病词不在 BROKEN_SUBSTITUTES、
 * 句式 3d 只认「垫词+句号」而这里是逗号、avgLen 落在"正常"区间。
 *
 * 后果比漏判更严重：这是**自证闭环**。humanize-bestof 专挑低分稿，
 * 而"把书面句改成满嘴你懂的"正好拿 0 分 → 优化方向被彻底带偏。
 * （v0.9.6 修掉过同类闭环：引擎造病词 → 标尺不认 → 专挑病词稿。这是它的换皮版本。）
 *
 * 本文件固化两个不变量，堵住同类回归：
 *   A. 真人写样本全部落在低分区（< 判定线）
 *   B. 引擎污染样本全部落在高分区（>= 判定线）
 *
 * 判定线说明：旧标尺时期用 40，现经标定改为 29——
 * 实测两组分离区间为「真人写 ≤27 ←→ 引擎污染 ≥30」。
 * 训练集 9 个 + 验证集 8 个样本，终版权重下零错判。
 *
 * 维护纪律：新增检测器或调整权重后**必须重跑本文件**。
 * 若某样本越界，先判断是"检测器过宽/过窄"还是"样本本就在灰区"，
 * 不要为了让测试变绿而删样本——样本是标定资产。
 */

