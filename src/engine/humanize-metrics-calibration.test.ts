describe("标尺区分度：真人写 vs 引擎污染（v0.9.7 盲区修复）", () => {
  describe("A. 真人写不被误伤", () => {
    for (const [label, text] of HUMAN_CASES) {
      it(`${label}：score < ${CUTOFF}`, () => {
        const r = aiScore(text);
        expect(r.score, `误伤：真人写被判 ${r.score} 分（structure=${r.structureHits}）`).toBeLessThan(
          CUTOFF,
        );
      });
    }
  });

  describe("B. 引擎污染不漏判", () => {
    for (const [label, text] of MACHINE_CASES) {
      it(`${label}：score >= ${CUTOFF}`, () => {
        const r = aiScore(text);
        expect(
          r.score,
          `漏判：引擎污染只判 ${r.score} 分（1=${r.formulaicHits} 病词=${r.brokenHits} 句式=${r.structureHits}）`,
        ).toBeGreaterThanOrEqual(CUTOFF);
      });
    }
  });

  it("盲区回归：垫词堆叠必须被判高分（旧标尺给 0 分）", () => {
    // 这是本文件存在的直接原因——旧标尺对这段给 0 分，导致 bestOf 专挑此类稿
    const r = aiScore("说真的，其实说白了，在当前背景下，企业要转型。讲真，老实讲，不是一蹴而就的。");
    expect(r.score).toBeGreaterThanOrEqual(CUTOFF);
  });

  it("误伤边界：单个合法垫词开头不应被判为引擎产物", () => {
    // 真人确实会写"说真的，…"，检测器必须看是否成堆，而不是看到垫词就扣分
    const r = aiScore("说真的，这事儿我琢磨好几天了。你要问我怎么看，我就直说吧。");
    expect(r.score).toBeLessThan(CUTOFF);
  });

  it("两组分数区间不重叠（分离性检验）", () => {
    const humanMax = Math.max(...HUMAN_CASES.map(([, t]) => aiScore(t).score));
    const machineMin = Math.min(...MACHINE_CASES.map(([, t]) => aiScore(t).score));
    expect(humanMax, `真人写最高 ${humanMax} 与引擎最低 ${machineMin} 出现重叠`).toBeLessThan(
      machineMin,
    );
  });
});

/**
 * 错别字项专项（v0.9.13）
 *
 * 起因：旧式 /大这?家/ 把正常词「大家」判成错字（每处 +30、两处 +60），而 typoCount
 * 只进 score 不外露 → 探针显示"各项命中 0"、分数却顶格，谁也查不出来。
 * 全仓语料该模式命中 30 处全是真人写法、真错字 0 处。修后必须同时锁两件事：
 * 正常词不罚、罚分项可诊断。
 */
describe("错别字项：不误伤「大家」，且命中数可外露诊断（v0.9.13）", () => {
  it("真人写法「大家早上好 / 提醒大家 / 请大家」零罚分", () => {
    const t = "大家早上好，今天我们来开周会。不过需要提醒大家的是，支付模块做了一次比对。请大家在上线当天保持通讯畅通。";
    const r = aiScore(t);
    expect(r.typoHits).toBe(0);
  });

  it("引擎真实造出的错字形态仍要抓到", () => {
    expect(aiScore("大这家店不错。").typoHits).toBe(1);
    expect(aiScore("规模再去年已经突破了 56.7 万亿元。").typoHits).toBe(1);
    expect(aiScore("大这家店不错。时候候我们再说。").typoHits).toBe(2);
  });

  it("纯靠错字顶到 60 分的文本，breakdown 必须解释得出这 60 分", () => {
    const r = aiScore("大这家店不错。大这家店也好。大这家店还行。");
    expect(r.typoHits).toBeGreaterThanOrEqual(2);
    expect(r.formulaicHits).toBe(0);
    expect(r.brokenHits).toBe(0);
    expect(r.structureHits).toBe(0);
    expect(r.score).toBeGreaterThanOrEqual(60);
  });

  it("任何被打分的文本都外露 typoHits（杜绝再一次隐藏计分）", () => {
    for (const t of ["", "今天很好。", "大这家店不错。", "值得注意的是，这事儿成了。"]) {
      expect(aiScore(t).typoHits, `aiScore(${JSON.stringify(t)}) 未外露 typoHits`).toBeTypeOf("number");
    }
  });
});
