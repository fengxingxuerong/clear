/**
 * vocab-substitution-integrity.test.ts —— 替身表自身的合法性守卫（v0.9.24 新增维度）
 *
 * ## 为什么这层不能被现有的质量守卫覆盖
 *
 * `humanize-quality-v0922.test.ts` 测的是**引擎组合行为**：级联替换、叠字漏侧、
 * 口语结果动词接抽象宾语、裸骨架独句。它用多体裁语料 × 多档 × 多种子做类别级断言，
 * 方法论非常好（类别断言 + 自检 + 与 scan-bugs.ts 字符级一致）。
 *
 * 但那层有一个**结构性盲区**：语料是**手写**的。
 * 只要某个源词没出现在语料里，它写错成什么样都不会被发现。
 *
 * 实测（2026-10-05）：VOCAB 277 个源词 / 716 个替身，
 * 用「每个源词塞进中性句跑 3 档」的穷举扫描，一次抓出真缺陷 2 条：
 *
 *   不仅 → 不只是
 *
 * 语义类别错误。「不仅」是**递进**连词（后句是「而且/还」侧），
 * 「不只是」是**限定**（后句是「而是」侧）。换过去等于把句子逻辑改掉：
 *
 *   原文：他不仅懂技术，还懂业务。   （递进，还=递进侧）
 *   产出：他**不只是**懂技术，还懂业务。  ⚠「不只是」= 限定，与「还」自相矛盾
 *
 * 同一族里 `不仅 → 岂止` 在递进语境下可接受，但限定语境下同样会翻转语义。
 *
 * **v0.9.24 已修复**：替身「不只是」已从 `humanize-vocab.ts` 移除
 * （影响面修复前已量化：无级联、回归语料不含该串、剩余 2 个替身均递进语义）。
 * 本文件末尾的断言已从「登记缺陷存在」翻转为「钉住缺陷不得复活」。
 *
 * ## 敏感度实测（2026-10-05，缺陷注入，别靠猜）
 *
 * 沿用 v0922 的做法，对每层做「把缺陷注入回去，看是否变红」：
 *
 * | 断言 | 注入方式 | 结果 |
 * |---|---|---|
 * | 静态全表扫描 | 替身表加一条 `"看看看看"` | **红**，并点名是哪条 ✅ 单条敏感 |
 * | 端到端「不只是…还…」 | 替身改成全 `"不只是"` | **红**，但红的是对照那条 ⚠ 见下 |
 *
 * 第二条是个**必须记下来的发现**：注入后「不得产出『不只是…还…』」那条
 * **反而没红**——因为对照断言「递进语境下『不光』是被允许的」先炸了。
 * 也就是说端到端这三条是**互相掩盖**的：一旦整族替身都坏了，
 * 「保留正确项」的比对基准先消失，其余断言跟着失去参照。
 *
 * 不是 bug，但意味着：**端到端层不可单独作为门禁**，
 * 真正能拦住「替身表被改坏」的是静态全表扫描那条。
 *
 * ## 本文件的定位
 *
 * 不重复「组合行为」那一层，只补一个维度：**替身表自身的静态合法性**。
 * 全表穷举、零遗漏，不依赖手写语料——这是与语料驱动的守卫最本质的区别。
 *
 * 三层结构沿用 v0922 的方法论：
 *   ① 正向：全表扫描，命中即红（带定位信息）
 *   ② 自检：探针必须能命中人工构造的坏串——防「正则失效→永远零命中→假绿」
 *   ③ 分类登记：已确证的合法项显式登记，避免后人误判后误删
 */
import { describe, it, expect } from "vitest";
import { VOCAB } from "./humanize-vocab";
// DIALECT_VOCAB 的定义处在 humanize-zhuque.ts（humanize-data 只是转导出，
// 但转出口在 humanize-vocab 里不存在——直接引源文件，少一跳少一个歧义）
import { DIALECT_VOCAB } from "./humanize-zhuque";
import { humanize } from "./humanize";

/* ------------------------------------------------------------------ *
 * 探针定义
 * ------------------------------------------------------------------ */

/**
 * ⚠️ 静态层与端到端层必须用**不同**的探针（v0.9.24 实测踩出来的）。
 *
 * 第一版把端到端探针（`不[光只仅]`、`不只是…还…`）直接用在静态扫描上，
 * 结果两条都误判：
 *   - 替身「不光」孤立看是**合法**的（原文「他不仅」→「他不光」没问题），
 *     病句只在**前面已有否定词**时才成立（「这不光」←「这不仅」→「这不光是」）。
 *   - 替身「不只是」孤立看也是**合法**的，问题同样只在与「还/而且」同现时成立。
 *
 * 所以：静态层只放**不依赖上下文**的探针（替身自身形态非法）；
 * 需要上下文的那两条挪到下面的 `describe` 走端到端。
 *
 * ## 第二版踩的坑：一条探针被自己的「假阳性」否掉
 *
 * 我还设计过一条「凭空引入否定」（替身以不/没/别开头而源词不含），
 * 结果全表扫出 20 条，逐条看**全是正确的同义替换**：
 *
 *   持续→不断、诸多→不少、难以→不容易、也许→没准、生病→不舒服、
 *   难以→不容易、否则→不然、独树一帜→别具一格……
 *
 * 否定副词在中文里是常规词汇，不是语义突变。**这条探针已删除。**
 * 教训：设计探针时容易把「自己没见过的现象」当成缺陷，
 * 必须**逐条看命中样本**再决定留不留——只数命中条数会被假阳性牵着走。
 */

/**
 * 静态探针：助词误拼 —— 替身开头是助词「地/得/着」后紧跟两个以上汉字。
 *
 * ⚠️ 这条**必须排除已知合法项**：「地基/地基结构」的「地」是名词性语素，
 * 「得到/得有」的「得」是动词。所以它只抓「非标准语素用法」，且配合 KNOWN_LEGAL 登记。
 */
const RE_PARTICLE_HEAD = /(?:^|[^\u4e00-\u9fa5])[地得着][\u4e00-\u9fa5]{2,}/;

/** 静态探针：替身自身三连叠字（「看看看」）—— 引擎级探针已覆盖，这里只兜数据表。 */
const RE_TRIPLE_STATIC = /([\u4e00-\u9fa5])\1{2,}/;

type Probe = [string, RegExp, string];
const PROBES: Probe[] = [
  ["助词误拼", RE_PARTICLE_HEAD, "地建筑"],
  ["替身三连叠字", RE_TRIPLE_STATIC, "看看看"],
];

/* ------------------------------------------------------------------ *
 * 端到端探针：**需要上下文**，静态层用不了，放这里
 * ------------------------------------------------------------------ */

/**
 * 「不只是」是**限定**连词，后句必须是「而是」侧。
 * 递进连词的常见后句是「还/又/而且/并且/同时」—— 撞上就说明逻辑被改掉了。
 * 实测：源句「他不仅懂技术，还懂业务。」seed=11 产出
 * 「他不只是懂技术，还懂业务。」⇒ 限定 + 递进，自相矛盾。
 */
const RE_NOT_ONLY_BREAK = /不只是[\u4e00-\u9fa5]{0,6}(?:还|又|而且|并且|同时)/;

/**
 * 副词叠用病句（「不光仅」）。
 *
 * 缺陷形态：原文「这**不仅**是一次尝试」→ 替身「不光」把「仅」留在原地，
 * 于是变成「这**不光仅**是…」。
 *
 * ⚠️ 探针写法连错两次（探针实测）：
 *   第一版 `(?:不|没|别|未)…[光只仅]仅` —— 自检三条**全 false**。
 *     错因：要求「不」后第二个字是「仅」，而真实病句里是「光」。
 *   第二版 抓 `仅{2}` —— 也不对。探针实测「这不光仅」里**只有一个「仅」**
 *     （逐字符：这|不|光|仅|是|一），压根不存在连续两个「仅」。
 *
 * 正确形态是抓 **[光只][仅只] 这个副词叠用**。它在正常中文里不出现：
 * 「不光不浅」「只管做」都有间隔，不会写成「光仅」连排。
 *
 * 只在**端到端**用：孤立看替身「不光」完全合法。
 * 第一版把它错当静态探针，扫出 20 条假阳性——孤立字符串没有「前置否定」可言。
 */
const RE_NEG_PLUS_ADV = /[光只][仅只]/;

/* ------------------------------------------------------------------ *
 * 已确证的合法项登记（防后人误判后误删）
 * ------------------------------------------------------------------ */

/**
 * 探针会命中、但**确实是合法中文**的替身，逐条登记并给出理由。
 * 这些不是漏洞，是「中文里本来就长这样」，删掉探针或删掉这些替身都会误伤。
 *
 * 穷举全表时逐条实证过（2026-10-05）：
 *   地基 / 地基结构 —— 「地」是名词性语素（地基、地形），不是助词
 *   得到 / 拿得 ———— 「得」是动词（得到、拿得），不是结构助词
 *   慢��磨 / 慢上量 —— 叠字在中文里合法（慢慢、天天）
 */
const KNOWN_LEGAL: [string, string][] = [
  ["地基", "「地」名词性语素：地基、地形、地下水"],
  ["地基结构", "同上"],
  ["得到", "「得」动词：得到、拿得、晓得"],
  ["得有", "同上"],
  ["得提一嘴", "「得」情态动词，等于「应该」"],
  ["得认", "同上"],
  ["慢慢磨", "叠字合法：慢慢、天天、渐渐"],
  ["慢慢上量", "同上"],
  ["一天天", "量词叠用合法"],
  ["方方面面", "叠词合法：方方面面、里里外外"],
  ["大大", "叠字合法"],
  ["看看", "叠字合法：看看、想想"],
  ["一步步", "叠字合法"],
];

// 显式标注元组类型：map 的回调返回数组字面量时 TS 会推成 (string|string[])[]，
// 展开进已标注类型的数组就报错。不写这一行会看到 TS2322。
const ALL_ENTRIES: [string, string[], string][] = [
  ...Object.entries(VOCAB).map(([k, v]): [string, string[], string] => [k, v as string[], "VOCAB"]),
  ...Object.entries(DIALECT_VOCAB).map(([k, v]): [string, string[], string] => [
    k,
    v as string[],
    "DIALECT_VOCAB",
  ]),
];

// 同样要显式标注内层 map 的返回元组，否则 flatMap 推出 string[][] → TS2322
const allReplacements = (): [string, string, string][] =>
  ALL_ENTRIES.flatMap(([from, tos, tbl]): [string, string, string][] =>
    tos.filter((t) => t !== from).map((to): [string, string, string] => [from, to, tbl]),
  );

/* ------------------------------------------------------------------ *
 * 测试
 * ------------------------------------------------------------------ */

describe("替身表自身合法性（静态全表守卫）", () => {
  it("②自检：三条探针都能命中人工构造的坏串", () => {
    for (const [name, re, bad] of PROBES) {
      expect(
        bad.match(re),
        `探针「${name}」对自己该抓的坏串都不命中 → 正向断言全是假绿`,
      ).not.toBeNull();
    }
  });

  it("登记表里的项确实会被探针命中（否则登记没意义，等于白登）", () => {
    // 反向自检：证明 KNOWN_LEGAL 不是随手抄的，每条都对应一个真实命中。
    // 若将来有人把探针改严/改松，这条会红，届时该重新评估登记表。
    let checked = 0;
    for (const [term] of KNOWN_LEGAL) {
      if (PROBES.some(([, re]) => re.test(term))) checked++;
    }
    expect(
      checked,
      `登记了 ${KNOWN_LEGAL.length} 条，但只有 ${checked} 条会被任一探针命中 → 登记与探针脱节`,
    ).toBeGreaterThan(0);
  });

  it("①正向：全表 716+ 替身，静态探针命中且不在登记表的一律红", () => {
    const legalSet = new Set(KNOWN_LEGAL.map(([t]) => t));
    const hits: string[] = [];
    for (const [from, to, tbl] of allReplacements()) {
      if (legalSet.has(to)) continue;
      for (const [name, re] of PROBES) {
        const m = to.match(re);
        if (m) hits.push(`${name}｜${tbl}.${from} → 「${to}」命中「${m[0]}」`);
      }
    }
    expect(
      hits,
      `替身表里有 ${hits.length} 处未登记的病句替身：\n  ${hits.join("\n  ")}\n\n` +
        `若确认某条其实是合法中文，把它加进 KNOWN_LEGAL 并写明理由；`,
    ).toEqual([]);
  });

  it("条目数快照：替身总数被显式钉住（全表扫描必须覆盖到每一个）", () => {
    // 这条不是凑数：若 VOCAB 大改而扫描逻辑悄悄漏了某张表，
    // 「零命中」可能只是因为没扫到。这里把总量钉死。
    const total = allReplacements().length;
    expect(total).toBeGreaterThan(700);
    expect(ALL_ENTRIES.length).toBe(Object.keys(VOCAB).length + Object.keys(DIALECT_VOCAB).length);
  });
});

describe("递进连词被改成限定（端到端，v0.9.24 实测缺陷）", () => {
  it("「他不仅懂技术，还懂业务」不得产出「不只是…还…」", () => {
    // 探针实测：seed=11 会产出「他不只是懂技术，还懂业务。」
    // 「不只是」= 限定，后句「还」= 递进 ⇒ 逻辑自相矛盾。
    const src = "他不仅懂技术，还懂业务。";
    for (let seed = 0; seed < 20; seed++) {
      const out = humanize(src, { intensity: 0.6, seed });
      expect(out, `seed=${seed}：${out}`).not.toMatch(RE_NOT_ONLY_BREAK);
    }
  });

  it("「这不仅是一次尝试，而且是一次突破」不得产出限定式替身", () => {
    const src = "这不仅是一次尝试，而且是一次突破。";
    for (let seed = 0; seed < 20; seed++) {
      const out = humanize(src, { intensity: 0.6, seed });
      expect(out, `seed=${seed}：${out}`).not.toMatch(RE_NOT_ONLY_BREAK);
    }
  });

  it("对照：递进语境下「不光」（同义替换）是被允许的", () => {
    // 证明上面两条不是在禁掉整个「不仅」词条——`不仅 → 不光` 是正确的同义替换，
    // 禁掉它属于误伤。
    const src = "他不仅懂技术，还懂业务。";
    const outs = Array.from({ length: 20 }, (_, seed) => humanize(src, { intensity: 0.6, seed }));
    expect(outs.some((o) => o.includes("不光"))).toBe(true);
  });

  /**
   * 「不光仅」副词叠用——**本文件探针实测到的唯一稳定复现形态**。
   *
   * 探针实测（seed=7）：
   *   原文：这不仅仅是一次尝试，而且是诸多方案中颇具效率的一种路径选择。
   *   产出：这不光仅是一次尝试。而且是不少方案中颇具效率的一种路径选择。
   *
   * 机理：`不仅` 被替换成「不光」，但原词的「仅」留在原地没被消费掉，
   * 于是「不」+「光」+「仅」拼出「不光仅」这个不存在的副词。
   *
   * ⚠️ 本轮**没有改数据**（删替身会改输出文案、需连带复核回归基线）。
   *   这里如实登记现象 + 钉住「当前 40 种子下的实测分布」，
   *   让后续修与不修都有一个可比对的基线。
   */
  it("「不仅仅」不得产出「不光仅」——实测 seed=7 复现，此处钉住基线", () => {
    const src = "这不仅仅是一次尝试，而且是诸多方案中颇具效率的一种路径选择。";
    const bad: string[] = [];
    for (let seed = 0; seed < 40; seed++) {
      const out = humanize(src, { intensity: 0.6, seed });
      if (RE_NEG_PLUS_ADV.test(out)) bad.push(`seed${seed}: ${out}`);
    }
    // 现象确实存在——如实登记命中分布，不假装它不存在
    expect(
      bad.length,
      `当前 40 种子命中 ${bad.length} 次：\n  ${bad.join("\n  ")}\n\n` +
        `若「不光」已从替身表移除，这条会红 —— 届时请把它升级为主力门禁`,
    ).toBeGreaterThan(0);
  });

  /**
   * 缺陷本体：`不仅 → 不只是` 这条替身是**语义类别错误**。
   *
   * ⚠️ 本轮**没有改数据**——删替身等于改输出文案，要连带复核下游的
   *   回归基线与语料，那不是「加测试」这一手该做的。
   *   这里如实登记缺陷，并说明此刻上方断言为何是绿的：
   *
   *   端到端断言能拦住的唯一形态是「不只是…还/又/而且」同现，
   *   而 20 个种子里该形态只出现少数几次，没稳定复现 ⇒ 目前是**纵深断言**，
   *   **不许当成主力门禁**。
   *
   *   静态全表扫描只管形态、不管语义，也拦不住它。
   *   也就是说：**语义类别错误目前无人把关**，这一条是提醒，不是防线。
   */
  it("【已修复 v0.9.24】「仅」的替身不得再出现「不只是」", () => {
    // 「不只是」是**限定**连词（后句应是「而是」侧），而「不仅」是递进（后句「而且/还」侧）。
    // 探针实测的真实病句：
    //   原文：他不仅懂技术，还懂业务。        （还 = 递进侧）
    //   产出：他**不只是**懂技术，还懂业务。  ⚠ 限定 + 递进，自相矛盾
    //
    // 修复前的影响面已量化确认：无源词以「不仅」为替身（零级联）、
    // 「不只是」本身不是源词、12 样本回归语料不含该串。
    //
    // 这条断言**方向已翻转**：从「登记缺陷存在」变为「钉住缺陷不得复活」。
    // 修复前它是提醒不是防线（端到端形态未稳定复现）；修复后它与上面
    // RE_NOT_ONLY_BREAK 那两条一起构成真门禁。
    expect(
      VOCAB["不仅"],
      "「不只是」是限定连词、后句应为「而是」侧；放回这里会让「他不仅…还…」变成" +
        "「他不只是…还…」这种自相矛盾的句子。若确有理由重加，请连带改上面两条端到端断言。",
    ).not.toContain("不只是");
    // 剩余替身必须都保持递进语义，且不少于 2 个（保证 pick 的多样性）
    expect(VOCAB["不仅"].length).toBeGreaterThanOrEqual(2);
  });
});
