/** 事实性错误签名：质检反馈里的"新增/遗漏"类问题。
 *  这类问题与"AI 痕迹"性质完全不同——它们是错误，不是风格，必须优先修掉而不是"消除"。 */
const FACT_ERROR_RE =
  /新增|编造|虚构|杜撰|原文无|原文没有|无此内容|没有此|凭空|遗漏|漏掉|缺失|被省略|被删|丢失|丢失了|篡改|改变原意|曲解/;

/** 多轮反馈改写：带着检测分与"残留痕迹清单"定向修订 */
export function buildRevisionPrompt(
  prev: string,
  score: number,
  target: number,
  critique: string[],
): string {
  // v0.8.9：质检反馈与评判痕迹原先混在一个列表里，模型会把
  // 「新增表姐、朋友等具体人物，原文无此内容」也当成"AI 痕迹"去"消除"，
  // 结果越改越偏（实测把议论文改成个人见闻、把专有名词删掉）。
  // 这里按语义分成两区：事实错误优先修，AI 痕迹其次。
  const errors = critique.filter((c) => FACT_ERROR_RE.test(c));
  const tells = critique.filter((c) => !FACT_ERROR_RE.test(c));

  const errorBlock = errors.length
    ? `
【必须先修的事实错误 —— 优先级高于降 AI 味】
${errors.map((c, i) => `${i + 1}. ${c}`).join("\n")}
处理方式：
- 属"新增/编造"的：把原文没有的那部分整段删掉，不要试图改写得自圆其说；
- 属"遗漏/被省略"的：从【当前文本】里找回对应内容补回去，找不到就按原意重写一句；
- 事实错误没修干净，AI 味降得再低也是废稿。
`
    : "";

  const tellText = tells.length
    ? tells.map((c, i) => `${i + 1}. ${c}`).join("\n")
    : "（检测员未列出具体痕迹，请按通用战术加强）";
  // 痕迹清单里命中篇章层问题时，附上对应的定向修法（朱雀主要看篇章层）
  const tactics = Array.from(
    new Set(tells.flatMap((c) => DISCOURSE_TACTICS.filter((t) => t.re.test(c)).map((t) => t.fix))),
  );
  const tacticBlock = tactics.length
    ? `\n对应修法（逐条执行）：\n${tactics.map((t, i) => `${i + 1}. ${t}`).join("\n")}\n`
    : "";
  return `下面这段文字已经被改写过，但 AI 检测员仍判它 ${score} 分（0=纯人写，100=纯AI），目标是压到 ${target} 分以下。
${errorBlock}
检测员指出的残留 AI 痕迹：
${tellText}
${tacticBlock}
请逐条消除上面的痕迹，同时注意：
- 【局部修改铁律】只动痕迹清单（含事实错误清单）指出的地方：未被点名的句子逐字保留（连标点都不许变）。
  实测依据：整篇重写的修订稿频繁"未优于当前最优"（90→90）甚至反向劣化（76→88），
  且重写会碰坏原本干净的部分、引入新编造。输出全文中与上一版不同的句子，
  原则上不超过痕迹条数 × 3 句。
- 每条痕迹都要处理，改完后自查一遍；
- （仅当痕迹清单提到节奏/句长/段落结构问题时）节奏更碎：多来几个三五字短句，段落重新切分——
  痕迹没提节奏就不要全局动刀，否则违反局部修改铁律；
- 口头禅别复读（"说真的/讲真/要我说"整篇各最多一次，但该用的时候要用），语气词整篇合计不超过 6 个，破折号整篇最多一次。

【严禁新增 —— 违反即整轮作废】
- 不得引入原文没有的人物、机构、案例、场景、数据、百分比、年份、地点。
  实测中已多次出现"编造某工厂的质检案例""编造四成岗位消失"这类问题：
  为了显"接地气"而现编例子，是比 AI 味更严重的硬伤。
- 想用例子时，只能沿用当前文本里已经存在的。
- 字数只减不增：本轮输出不得超过【当前文本】的长度。降 AI 味靠删减和重组，
  不靠扩写——扩写出来的"细节"几乎必然是编的。

原有事实、数字、逻辑关系依然一个都不能变。

【当前文本】
${prev}`;
}
